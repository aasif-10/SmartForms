export function getCategoryIcon(categoryKey: string, size = 15) {
  switch (categoryKey) {
    case 'personal':
      return <UserIcon size={size} />;
    case 'contact':
      return <MailIcon size={size} />;
    case 'identification':
      return <IdIcon size={size} />;
    case 'education':
      return <EducationIcon size={size} />;
    case 'address':
      return <MapPinIcon size={size} />;
    case 'professional':
      return <BriefcaseIcon size={size} />;
    default:
      return <TagIcon size={size} />;
  }
}
